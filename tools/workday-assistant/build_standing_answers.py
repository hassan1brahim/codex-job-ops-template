"""Generate standing-answers.js (loaded by the extension) from profile/application-defaults.json."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "profile" / "application-defaults.json"
EXAMPLE = ROOT / "profile" / "application-defaults.example.json"
TARGET = Path(__file__).resolve().parent / "standing-answers.js"


def build() -> str:
    data = json.loads((SOURCE if SOURCE.exists() else EXAMPLE).read_text())
    data.pop("_comment", None)
    c = data["contact"]
    full = f"{c['firstName']} {c['lastName']}"
    contact_qa = [
        {"q": r"^(legal )?first name", "a": c["firstName"]},
        {"q": r"^(legal )?last name|^surname", "a": c["lastName"]},
        {"q": r"^(full|legal) name$|^name$", "a": full},
        {"q": r"^(home )?e-?mail", "a": c["email"]},
        {"q": r"^phone( number)?$|^mobile", "a": c["phone"]},
        {"q": r"^address( line)? 1|^street address", "a": c["address1"]},
        {"q": r"^city$", "a": c["city"]},
        {"q": r"^state(/province)?$", "a": c["state"]},
        {"q": r"^zip|^postal", "a": c["postalCode"]},
        {"q": r"^country$", "a": c["country"]},
        {"q": r"linkedin", "a": c["linkedin"]},
        {"q": r"github", "a": c["github"]},
    ]
    data["qa"] = contact_qa + data["qa"]
    body = json.dumps(data, indent=2, ensure_ascii=False)
    return (
        "// GENERATED by build_standing_answers.py from profile/application-defaults.json. Do not edit.\n"
        f"globalThis.JOB_OPS_STANDING_ANSWERS = Object.freeze({body});\n"
    )


if __name__ == "__main__":
    TARGET.write_text(build())
    print(f"wrote {TARGET.relative_to(ROOT)}")
